import datetime
from typing import TypeAlias

TimeIntervals: TypeAlias = list[tuple[str, str]]


def time_range(
    start_time: str,
    end_time: str,
    number_of_intervals: int = 1,
    gap_between_intervals_s: int = 0,
) -> TimeIntervals:
    """Create a sequence of time ranges.

    The created intervals will fill the interval between `start_time` and `end_time`.
    If a gap between intervals is specified, there will be time gaps between the start
    of one interval and the end of the previous.

    Args:
        start_time: str
            Date string in `YYYY-mm-dd hh-mm-ss` format, specifying when to start the
            first interval.
        end_time: str
            Date string in `YYYY-mm-dd hh-mm-ss` format, specifying when to end the
            final interval.
        number_of_intervals: int
            Number of equal-length intervals to divide the time range into.
        gap_between_intervals_s: int
            Number of seconds to place between the end of one interval and the beginning
            of the next.

    Returns:
        list[tuple[str, str]]:
            List of tuples, each with 2 elements containing strings of the format
            `YYYY-mm-dd hh-mm-ss`. The 0-th such element contains the start time of an
            interval, and the 1-st the end time of that interval. The list as a whole
            contains all the intervals that were generated by the function.
    """
    start_time_s = datetime.datetime.strptime(start_time, "%Y-%m-%d %H:%M:%S")
    end_time_s = datetime.datetime.strptime(end_time, "%Y-%m-%d %H:%M:%S")
    d = (
        end_time_s - start_time_s
    ).total_seconds() / number_of_intervals + gap_between_intervals_s * (
        1 / number_of_intervals - 1
    )
    sec_range = [
        (
            start_time_s
            + datetime.timedelta(seconds=i * d + i * gap_between_intervals_s),
            start_time_s
            + datetime.timedelta(seconds=(i + 1) * d + i * gap_between_intervals_s),
        )
        for i in range(number_of_intervals)
    ]
    return [
        (ta.strftime("%Y-%m-%d %H:%M:%S"), tb.strftime("%Y-%m-%d %H:%M:%S"))
        for ta, tb in sec_range
    ]


def compute_overlap_time(range1: TimeIntervals, range2: TimeIntervals) -> TimeIntervals:
    """Computes the overlap ranges two collections of time intervals.

    Args:
        range1: list[tuple[str, str]]
            Collection of time intervals. Has the same structure and interpretation
            as the output of `time_range`.
        range2: list[tuple[str, str]]
            Collection of time intervals. Has the same structure and interpretation
            as the output of `time_range`.

    Returns:
        list[tuple[str, str]]:
            Time ranges corresponding to the overlaps between the two given ranges.
    """
    overlap_time = []
    for start1, end1 in range1:
        for start2, end2 in range2:
            low = max(start1, start2)
            high = min(end1, end2)
            overlap_time.append((low, high))
    return overlap_time
